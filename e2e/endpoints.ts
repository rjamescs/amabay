/**
 * API surface model for the Playwright suite.
 *
 * Every endpoint of the amabay API is described once, here, as a plain object.
 * Tests reference these objects instead of hard-coding method/path strings, so
 * a route change is a one-line edit in this file.
 *
 * `generateBody()` produces a request body for any endpoint that requires one
 * (POST create, PATCH update). Endpoints with `requiresBody: false` yield
 * `undefined`.
 */

export type HttpMethod = 'GET' | 'POST' | 'PATCH' | 'DELETE';

/** Which body shape an endpoint expects, if any. */
export type BodyKind = 'create' | 'update';

export interface Endpoint {
  /** Stable key, also used in test titles. */
  name: string;
  method: HttpMethod;
  /** True when the endpoint expects a JSON request body. */
  requiresBody: boolean;
  /** The body shape to generate; only meaningful when requiresBody is true. */
  bodyKind?: BodyKind;
  /**
   * Builds the request path. Collection endpoints ignore the argument;
   * item endpoints interpolate the id.
   */
  path: (id?: number | string) => string;
  /** Human-readable summary for documentation / test output. */
  description: string;
}

