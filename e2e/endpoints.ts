// ---------------------------------------------------------------------------
// Request body generation.
// ---------------------------------------------------------------------------

/** The full item payload accepted by the create endpoint. */
export interface ItemBody {
  title: string;
  price: number;
  quantity: number;
  description?: string;
  image?: string;
}

// Monotonic counter so titles/markers are unique within a run, even if two
// bodies are generated in the same millisecond.
let seq = 0;

/** A run-unique token, handy for isolating a test's rows via `?q=`. */
export function uniqueMarker(prefix = 'e2e'): string {
  seq += 1;
  return `${prefix}-${Date.now()}-${seq}`;
}

/** Round to 2 decimals to keep prices realistic for an ecommerce catalog. */
function money(): number {
  return Number((Math.random() * 100 + 1).toFixed(2));
}

/**
 * Generate a request body for the given endpoint.
 *
 * - `create` endpoints get a complete, valid item (all required fields plus
 *   optional description/image).
 * - `update` endpoints get a valid partial body containing a single field, so
 *   it satisfies the "at least one field" rule without touching everything.
 * - Endpoints that take no body return `undefined`.
 *
 * `overrides` are shallow-merged last, so a test can pin or invalidate any
 * field (e.g. `{ price: -1 }` to exercise the validation path).
 */
export function generateBody(
  endpoint: Endpoint,
  overrides: Partial<ItemBody> = {}
): ItemBody | Partial<ItemBody> | undefined {
  if (!endpoint.requiresBody) return undefined;

  if (endpoint.bodyKind === 'create') {
    const marker = uniqueMarker();
    const body: ItemBody = {
      title: `Item ${marker}`,
      price: money(),
      quantity: Math.floor(Math.random() * 50) + 1,
      description: `Autogenerated item ${marker}`,
      image: 'https://example.com/item.jpg',
    };
    return { ...body, ...overrides };
  }

  // bodyKind === 'update' — a valid, non-empty partial update.
  const partial: Partial<ItemBody> = { price: money() };
  return { ...partial, ...overrides };
}
